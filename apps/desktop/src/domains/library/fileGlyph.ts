import {
  BookIcon,
  FileAudioIcon,
  FileCodeIcon,
  FileCsvIcon,
  FileDocIcon,
  FileHtmlIcon,
  FileIcon,
  FileImageIcon,
  FileMdIcon,
  FilePdfIcon,
  FilePptIcon,
  FileTextIcon,
  FileVideoIcon,
  FileXlsIcon,
  FileZipIcon,
  FolderIcon,
  type Icon,
} from "@phosphor-icons/react";

/// Extension to glyph, its own module so fast refresh keeps working. Every
/// glyph inherits the row's ink: "this is a PDF" is not signal (UI.md rule 1).
const BY_EXT: Record<string, Icon> = {
  pdf: FilePdfIcon,
  md: FileMdIcon,
  markdown: FileMdIcon,
  txt: FileTextIcon,
  rtf: FileTextIcon,
  doc: FileDocIcon,
  docx: FileDocIcon,
  odt: FileDocIcon,
  epub: BookIcon,
  xls: FileXlsIcon,
  xlsx: FileXlsIcon,
  csv: FileCsvIcon,
  ppt: FilePptIcon,
  pptx: FilePptIcon,
  html: FileHtmlIcon,
  htm: FileHtmlIcon,
  json: FileCodeIcon,
  xml: FileCodeIcon,
  yaml: FileCodeIcon,
  yml: FileCodeIcon,
  png: FileImageIcon,
  jpg: FileImageIcon,
  jpeg: FileImageIcon,
  gif: FileImageIcon,
  webp: FileImageIcon,
  tiff: FileImageIcon,
  tif: FileImageIcon,
  heic: FileImageIcon,
  bmp: FileImageIcon,
  mp3: FileAudioIcon,
  wav: FileAudioIcon,
  m4a: FileAudioIcon,
  aac: FileAudioIcon,
  flac: FileAudioIcon,
  ogg: FileAudioIcon,
  oga: FileAudioIcon,
  opus: FileAudioIcon,
  amr: FileAudioIcon,
  mp4: FileVideoIcon,
  mov: FileVideoIcon,
  m4v: FileVideoIcon,
  webm: FileVideoIcon,
  mkv: FileVideoIcon,
  avi: FileVideoIcon,
  wmv: FileVideoIcon,
  mpeg: FileVideoIcon,
  mpg: FileVideoIcon,
  "3gp": FileVideoIcon,
  zip: FileZipIcon,
};

/// `ext` is the host's: lowercase, no dot, and nothing here parses a name.
export function fileGlyph(ext: string, isDir: boolean): Icon {
  if (isDir) return FolderIcon;
  return BY_EXT[ext] ?? FileIcon;
}
